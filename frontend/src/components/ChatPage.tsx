import { Box, Button, Chip, Typography } from '@mui/material';
import { useEffect } from 'react';
import { Navigate, useMatch, useNavigate } from 'react-router-dom';
import { useChatActions } from '../hooks/useChatActions';
import { abortCurrent, loadConversation, resetChat } from '../store/chatSlice';
import { useAppDispatch, useAppSelector, useAppStore } from '../store/hooks';
import Composer from './Composer';
import MessageList from './MessageList';

const SUGGESTIONS = ['What can you do?', 'Show me a table', 'Show me an image', 'Write some code', 'Let me choose a topic'];

export default function ChatPage() {
  const dispatch = useAppDispatch();
  const store = useAppStore();
  const navigate = useNavigate();
  const { send } = useChatActions();

  const isHome = useMatch('/');
  const convMatch = useMatch('/c/:conversationId');
  const routeId = convMatch?.params.conversationId ?? null;

  const user = useAppSelector((s) => s.auth.user);
  const { messages, loading, error } = useAppSelector((s) => s.chat);

  // The URL is the source of truth for which conversation is open.
  useEffect(() => {
    if (!user) {
      abortCurrent();
      dispatch(resetChat());
      if (routeId) navigate('/', { replace: true });
      return;
    }
    if (!routeId) {
      abortCurrent();
      dispatch(resetChat());
      return;
    }
    // When a message creates a new conversation the store already knows its id; don't reload it.
    if (store.getState().chat.activeId !== routeId) {
      abortCurrent();
      dispatch(loadConversation(routeId));
    }
  }, [routeId, user, dispatch, store, navigate]);

  if (!isHome && !convMatch) return <Navigate to="/" replace />;

  const isEmpty = messages.length === 0 && !loading && !error;

  return (
    <Box sx={{ flex: 1, minHeight: 0, display: 'flex', flexDirection: 'column' }}>
      {!isEmpty && <MessageList />}

      <Box
        sx={{
          display: 'flex',
          flexDirection: 'column',
          alignItems: 'center',
          px: 2,
          pb: isEmpty ? 10 : 1.5,
          ...(isEmpty ? { flex: 1, justifyContent: 'center' } : {}),
        }}
      >
        {isEmpty && (
          <Typography variant="h4" component="h1" sx={{ mb: 3, textAlign: 'center' }}>
            Where should we begin?
          </Typography>
        )}
        <Box sx={{ width: '100%', maxWidth: 768 }}>
          <Composer />
        </Box>
        {isEmpty ? (
          <Box sx={{ display: 'flex', flexWrap: 'wrap', justifyContent: 'center', gap: 1, mt: 2, maxWidth: 768 }}>
            {SUGGESTIONS.map((s) => (
              <Chip key={s} label={s} variant="outlined" onClick={() => send(s)} sx={{ fontWeight: 500, height: 36, borderRadius: 999 }} />
            ))}
          </Box>
        ) : (
          <Typography variant="caption" color="text.secondary" sx={{ mt: 1, textAlign: 'center' }}>
            ChatClone is a demo. Replies are scripted, not generated by an AI model.
          </Typography>
        )}
        {error && messages.length === 0 && (
          <Button sx={{ mt: 2 }} onClick={() => navigate('/')}>
            Start a new chat
          </Button>
        )}
      </Box>
    </Box>
  );
}
